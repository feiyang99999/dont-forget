export type MessageKey = keyof typeof zh;

export function t(lang: Lang, key: MessageKey): string {
  return (lang === 'en' ? en : zh)[key];
}

export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ''));
}

export function categoryLabel(lang: Lang, category: Category): string {
  return t(lang, `cat_${category}`);
}

export function daysText(lang: Lang, days: number): string {
  if (days < 0) return fill(t(lang, 'overdue'), { n: -days });
  if (days === 0) return t(lang, 'dueToday');
  if (days === 1) return t(lang, 'dueTomorrow');
  return fill(t(lang, 'daysLeft'), { n: days });
}

export function ocrPhase(lang: Lang, status: string): string {
  const key = status.toLowerCase();
  if (key.includes('core')) return t(lang, 'ocrCore');
  if (key.includes('language') || key.includes('trained')) return t(lang, 'ocrLang');
  if (key.includes('initial')) return t(lang, 'ocrInit');
  if (key.includes('recogn')) return t(lang, 'ocrRead');
  return t(lang, 'ocrWork');
}
